"""Generate every app icon, splash and notification icon from the logo PNGs.

Run: python tool/gen_brand_assets.py   (needs Pillow: pip install pillow)

Sources (assets/branding/source/):
  * moneytrail-app-icon.png       square icon, white "M" mark on VarSys blue
  * moneytrail-logo-horizontal.png full logo with the VarSys MoneyTrail wordmark

The white mark is lifted out of the square icon as an alpha mask (its red
channel goes from the background's 17 to white's 255), so the adaptive
foreground, the Android 13 themed icon, the notification icon and the iOS
dark/tinted variants all use the same shape.
"""
from pathlib import Path

from PIL import Image, ImageChops, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'assets/branding/source'
RES = ROOT / 'android/app/src/main/res'
BLUE = (17, 84, 234)  # background of the square icon
DARK_MARK = (91, 143, 255)  # iOS dark variant: mark on the system backdrop
DENSITIES = {'mdpi': 1, 'hdpi': 1.5, 'xhdpi': 2, 'xxhdpi': 3, 'xxxhdpi': 4}
SS = 4  # supersampling for masks

square = Image.open(SRC / 'moneytrail-app-icon.png').convert('RGB')
_red = square.split()[0]
# Floor at 24: the background has a little noise (red 17-19) that would
# otherwise widen the crop box.
_FLOOR = BLUE[0] + 24
_mask = _red.point(lambda v: 0 if v < _FLOOR else min(255, round((v - _FLOOR) * 255 / (255 - _FLOOR))))
MARK = _mask.crop(_mask.getbbox())  # alpha mask of the white mark, tight bbox


def out(rel: str) -> Path:
    p = ROOT / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    print(rel)
    return p


def mark_layer(size: int, width_frac: float, color=(255, 255, 255)) -> Image.Image:
    """Transparent square with the mark centred, `width_frac` of the canvas wide."""
    w = round(size * width_frac)
    h = round(w * MARK.height / MARK.width)
    m = MARK.resize((w, h), Image.LANCZOS)
    layer = Image.new('RGBA', (size, size), color + (0,))
    solid = Image.new('RGBA', (w, h), color + (255,))
    solid.putalpha(m)
    layer.alpha_composite(solid, ((size - w) // 2, (size - h) // 2))
    return layer


def shape_mask(size: int, shape: str) -> Image.Image:
    big = Image.new('L', (size * SS, size * SS), 0)
    d = ImageDraw.Draw(big)
    box = (0, 0, size * SS - 1, size * SS - 1)
    if shape == 'round':
        d.ellipse(box, fill=255)
    elif shape == 'roundrect':
        d.rounded_rectangle(box, radius=round(size * SS * 0.22), fill=255)
    else:
        d.rectangle(box, fill=255)
    return big.resize((size, size), Image.LANCZOS)


def icon(size: int, shape: str = 'square', width_frac: float = 0.6) -> Image.Image:
    img = Image.new('RGBA', (size, size), BLUE + (255,))
    img.alpha_composite(mark_layer(size, width_frac))
    img.putalpha(ImageChops.multiply(img.getchannel('A'), shape_mask(size, shape)))
    return img


# Square icon reference for docs and the in-app BrandMark.
icon(512).save(out('assets/branding/app_icon.png'))

# ---------------------------------------------------------------- Android
for old in ['drawable/ic_launcher_foreground.xml', 'drawable/ic_launcher_monochrome.xml', 'drawable/ic_stat_varsys.xml']:
    (RES / old).unlink(missing_ok=True)
out('android/app/src/main/res/drawable/ic_launcher_background.xml').write_text(
    '<?xml version="1.0" encoding="utf-8"?>\n'
    '<!-- GENERATED by tool/gen_brand_assets.py. Adaptive icon background: MoneyTrail blue. -->\n'
    '<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">\n'
    '    <solid android:color="#%02X%02X%02X" />\n'
    '</shape>\n' % BLUE,
    encoding='utf-8',
)
for d, k in DENSITIES.items():
    # Adaptive foreground / themed monochrome: 108dp canvas; the mark (52dp
    # wide) stays inside the 66dp safe circle.
    fg = mark_layer(round(108 * k), 52 / 108)
    fg.save(out(f'android/app/src/main/res/drawable-{d}/ic_launcher_foreground.png'))
    fg.save(out(f'android/app/src/main/res/drawable-{d}/ic_launcher_monochrome.png'))
    # Notification small icon: white on transparent, 24dp with 2dp padding.
    mark_layer(round(24 * k), 22 / 24).save(out(f'android/app/src/main/res/drawable-{d}/ic_stat_varsys.png'))
    # Legacy launchers (minSdk 30 always uses the adaptive icon).
    icon(round(48 * k), 'roundrect').save(out(f'android/app/src/main/res/mipmap-{d}/ic_launcher.png'))
    icon(round(48 * k), 'round').save(out(f'android/app/src/main/res/mipmap-{d}/ic_launcher_round.png'))
    # Splash: Android 12+ masks a 288dp icon to a 192dp circle; a 180dp blue
    # disc with the mark reads on both splash backgrounds.
    sz = round(288 * k)
    splash = Image.new('RGBA', (sz, sz), (0, 0, 0, 0))
    disc = icon(round(180 * k), 'round', 0.62)
    splash.alpha_composite(disc, ((sz - disc.width) // 2, (sz - disc.height) // 2))
    splash.save(out(f'android/app/src/main/res/drawable-{d}/splash_icon.png'))

# -------------------------------------------------------------------- iOS
appicon = ROOT / 'ios/Runner/Assets.xcassets/AppIcon.appiconset'
# iOS masks the corners itself and rejects default icons with alpha.
icon(1024).convert('RGB').save(out(f'{appicon.relative_to(ROOT).as_posix()}/AppIcon-1024.png'))
mark_layer(1024, 0.6, DARK_MARK).save(out(f'{appicon.relative_to(ROOT).as_posix()}/AppIcon-1024-dark.png'))
tinted = Image.new('RGBA', (1024, 1024), (0, 0, 0, 255))
tinted.alpha_composite(mark_layer(1024, 0.6))
tinted.convert('RGB').save(out(f'{appicon.relative_to(ROOT).as_posix()}/AppIcon-1024-tinted.png'))
launch = 'ios/Runner/Assets.xcassets/LaunchImage.imageset'
for name, s in [('LaunchImage.png', 120), ('LaunchImage@2x.png', 240), ('LaunchImage@3x.png', 360)]:
    icon(s, 'round', 0.62).save(out(f'{launch}/{name}'))

# --------------------------------------------------------------- previews
prev = 'assets/branding/previews'
for old in ['ios_dark_variant.png', 'themed_on_light.png', 'themed_on_dark.png']:
    (ROOT / prev / old).unlink(missing_ok=True)
for name, page in [('icon_on_light', (248, 250, 252)), ('icon_on_dark', (9, 9, 11))]:
    canvas = Image.new('RGBA', (40 + 288 + 40 + 144 + 40 + 48 + 40, 288 + 80), page + (255,))
    x = 40
    for s in (288, 144, 48):
        # Launchers show the inner 72dp of the 108dp canvas.
        canvas.alpha_composite(icon(s, 'roundrect', 52 / 72), (x, 40 + (288 - s) // 2))
        x += s + 40
    canvas.convert('RGB').save(out(f'{prev}/{name}.png'))
